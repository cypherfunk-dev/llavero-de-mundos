/* Mayúsculas acentuadas: a 5x7 no cabe la tilde, se dibujan sin ella. */
static uint32_t fold(uint32_t cp)
{
    switch (cp) {
    case 0x00C1: return 'A';
    case 0x00C9: return 'E';
    case 0x00CD: return 'I';
    case 0x00D3: case 0x00D6: return 'O';
    case 0x00DA: case 0x00DC: return 'U';
    default: return cp;
    }
}

const uint8_t *font_glyph(uint32_t cp)
{
    cp = fold(cp);
    if (cp >= 32 && cp <= 126)
        return ASCII[cp - 32];
    for (unsigned i = 0; i < sizeof(EXTRA) / sizeof(EXTRA[0]); i++)
        if (EXTRA[i].cp == cp)
            return EXTRA[i].rows;
    return ASCII['?' - 32];
}

uint32_t font_utf8_next(const char **s)
{
    const unsigned char *p = (const unsigned char *)*s;
    uint32_t cp;
    int extra;
    if (p[0] < 0x80) {
        cp = p[0];
        extra = 0;
    } else if ((p[0] & 0xE0) == 0xC0) {
        cp = p[0] & 0x1F;
        extra = 1;
    } else if ((p[0] & 0xF0) == 0xE0) {
        cp = p[0] & 0x0F;
        extra = 2;
    } else if ((p[0] & 0xF8) == 0xF0) {
        cp = p[0] & 0x07;
        extra = 3;
    } else {
        *s += 1;
        return '?';
    }
    for (int i = 1; i <= extra; i++) {
        if ((p[i] & 0xC0) != 0x80) {
            *s += i;
            return '?';
        }
        cp = (cp << 6) | (p[i] & 0x3F);
    }
    *s += extra + 1;
    return cp;
}
